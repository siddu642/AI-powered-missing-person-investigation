def explain_prediction(df):

    latest = df.iloc[-1]

    explanations = []

    if latest["speed_kmh"] < 5:

        explanations.append(
            "Low recent movement speed"
        )

    elif latest["speed_kmh"] < 30:

        explanations.append(
            "Movement speed is within a typical local travel range"
        )

    else:

        explanations.append(
            "Recent movement speed is relatively high"
        )

    if latest["hour"] >= 22 or latest["hour"] <= 5:

        explanations.append(
            "The latest movement occurred during nighttime hours"
        )

    if latest["rolling_speed"] > 40:

        explanations.append(
            "Recent trajectory contains sustained movement"
        )

    else:

        explanations.append(
            "Recent trajectory indicates relatively slow movement"
        )

    if latest["anomaly"]:

        explanations.append(
            "The latest movement was identified as anomalous"
        )

    else:

        explanations.append(
            "The latest movement does not appear strongly anomalous"
        )

    return explanations


