def haversine(lat1, lon1, lat2, lon2):
    """
    Calculate distance between two GPS coordinates in kilometers.
    """

    R = 6371.0

    lat1 = np.radians(lat1)
    lat2 = np.radians(lat2)

    dlat = np.radians(lat2 - lat1)
    dlon = np.radians(lon2 - lon1)

    a = (
        np.sin(dlat / 2) ** 2
        + np.cos(lat1)
        * np.cos(lat2)
        * np.sin(dlon / 2) ** 2
    )

    return 2 * R * np.arcsin(np.sqrt(a))


def bearing(lat1, lon1, lat2, lon2):
    """
    Calculate movement direction.
    """

    lat1 = np.radians(lat1)
    lat2 = np.radians(lat2)

    dlon = np.radians(lon2 - lon1)

    x = np.sin(dlon) * np.cos(lat2)

    y = (
        np.cos(lat1) * np.sin(lat2)
        - np.sin(lat1) * np.cos(lat2) * np.cos(dlon)
    )

    angle = np.degrees(np.arctan2(x, y))

    return (angle + 360) % 360


def generate_demo_data(n=2500):
    """
    Generate realistic synthetic trajectory data.

    Used when no GeoLife dataset is supplied.
    """

    np.random.seed(42)

    start_lat = 23.2599
    start_lon = 77.4126

    timestamps = []
    latitudes = []
    longitudes = []

    current_lat = start_lat
    current_lon = start_lon

    current_time = datetime(2026, 1, 1, 8, 0, 0)

    for i in range(n):

        timestamps.append(current_time)

        # Random movement
        movement_lat = np.random.normal(0, 0.0008)
        movement_lon = np.random.normal(0, 0.0008)

        current_lat += movement_lat
        current_lon += movement_lon

        latitudes.append(current_lat)
        longitudes.append(current_lon)

        current_time += timedelta(minutes=5)

    df = pd.DataFrame({
        "timestamp": timestamps,
        "latitude": latitudes,
        "longitude": longitudes
    })

    return df


def clean_gps_data(df):
    """
    Standardize GPS dataframe.
    """

    df = df.copy()

    # Lowercase columns
    df.columns = [
        str(c).strip().lower().replace(" ", "_")
        for c in df.columns
    ]

    # Detect latitude
    lat_candidates = [
        "latitude",
        "lat",
        "gps_latitude",
        "y"
    ]

    lon_candidates = [
        "longitude",
        "lon",
        "lng",
        "gps_longitude",
        "x"
    ]

    time_candidates = [
        "timestamp",
        "datetime",
        "date_time",
        "date",
        "time"
    ]

    lat_col = None
    lon_col = None
    time_col = None

    for c in lat_candidates:
        if c in df.columns:
            lat_col = c
            break

    for c in lon_candidates:
        if c in df.columns:
            lon_col = c
            break

    for c in time_candidates:
        if c in df.columns:
            time_col = c
            break

    # GeoLife special format
    if lat_col is None or lon_col is None:

        numeric_cols = []

        for col in df.columns:

            converted = pd.to_numeric(
                df[col],
                errors="coerce"
            )

            if converted.notna().sum() > len(df) * 0.5:
                numeric_cols.append(col)

        if len(numeric_cols) >= 2:

            possible = []

            for col in numeric_cols:

                values = pd.to_numeric(
                    df[col],
                    errors="coerce"
                )

                if values.between(-90, 90).mean() > 0.8:
                    possible.append(col)

            if len(possible) >= 2:
                lat_col = possible[0]
                lon_col = possible[1]

    if lat_col is None or lon_col is None:
        raise ValueError(
            "Could not identify latitude and longitude columns."
        )

    df["latitude"] = pd.to_numeric(
        df[lat_col],
        errors="coerce"
    )

    df["longitude"] = pd.to_numeric(
        df[lon_col],
        errors="coerce"
    )

    # Timestamp
    if time_col is not None:

        df["timestamp"] = pd.to_datetime(
            df[time_col],
            errors="coerce"
        )

    else:

        # Generate artificial timestamps
        df["timestamp"] = pd.date_range(
            start="2026-01-01",
            periods=len(df),
            freq="5min"
        )

    df = df[
        [
            "timestamp",
            "latitude",
            "longitude"
        ]
    ]

    df = df.dropna()

    df = df[
        df["latitude"].between(-90, 90)
        & df["longitude"].between(-180, 180)
    ]

    df = df.sort_values("timestamp")

    df = df.drop_duplicates()

    df = df.reset_index(drop=True)

    return df


def read_csv_from_zip(uploaded_file):
    """
    Try to read GPS files from GeoLife ZIP.
    """

    records = []

    with zipfile.ZipFile(uploaded_file) as z:

        names = z.namelist()

        for name in names:

            lower = name.lower()

            if not lower.endswith(".plt"):
                continue

            try:

                with z.open(name) as f:

                    raw = f.read()

                text = raw.decode(
                    "utf-8",
                    errors="ignore"
                )

                rows = []

                for line in text.splitlines():

                    parts = line.strip().split(",")

                    if len(parts) >= 6:

                        try:

                            lat = float(parts[0])
                            lon = float(parts[1])

                            date = parts[5]
                            time_value = (
                                parts[6]
                                if len(parts) > 6
                                else "00:00:00"
                            )

                            timestamp = pd.to_datetime(
                                date + " " + time_value,
                                errors="coerce"
                            )

                            rows.append(
                                [
                                    timestamp,
                                    lat,
                                    lon
                                ]
                            )

                        except Exception:
                            continue

                if rows:

                    temp = pd.DataFrame(
                        rows,
                        columns=[
                            "timestamp",
                            "latitude",
                            "longitude"
                        ]
                    )

                    records.append(temp)

            except Exception:
                continue

    if not records:
        return None

    df = pd.concat(
        records,
        ignore_index=True
    )

    return df


