def train_location_model(df):

    data = df.copy()

    data["target_lat"] = (
        data["latitude"].shift(-1)
    )

    data["target_lon"] = (
        data["longitude"].shift(-1)
    )

    data = data.dropna()

    features = [
        "latitude",
        "longitude",
        "hour",
        "day_of_week",
        "speed_kmh",
        "bearing",
        "rolling_speed"
    ]

    X = data[features]

    y_lat = data["target_lat"]

    y_lon = data["target_lon"]

    # Keep training reasonably fast for Streamlit
    max_samples = 12000

    if len(X) > max_samples:

        sample_indices = np.linspace(
            0,
            len(X) - 1,
            max_samples
        ).astype(int)

        X = X.iloc[sample_indices]

        y_lat = y_lat.iloc[sample_indices]

        y_lon = y_lon.iloc[sample_indices]

    model_lat = RandomForestRegressor(
        n_estimators=80,
        max_depth=15,
        random_state=42,
        n_jobs=-1
    )

    model_lon = RandomForestRegressor(
        n_estimators=80,
        max_depth=15,
        random_state=42,
        n_jobs=-1
    )

    model_lat.fit(
        X,
        y_lat
    )

    model_lon.fit(
        X,
        y_lon
    )

    return (
        model_lat,
        model_lon,
        features
    )


def predict_next_location(
    df,
    model_lat,
    model_lon,
    features
):

    latest = df.iloc[-1]

    X = pd.DataFrame(
        [[
            latest["latitude"],
            latest["longitude"],
            latest["hour"],
            latest["day_of_week"],
            latest["speed_kmh"],
            latest["bearing"],
            latest["rolling_speed"]
        ]],
        columns=features
    )

    predicted_lat = model_lat.predict(X)[0]

    predicted_lon = model_lon.predict(X)[0]

    return predicted_lat, predicted_lon


