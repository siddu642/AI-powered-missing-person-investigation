def detect_anomalies(df, contamination=0.03):

    data = df.copy()

    features = [
        "latitude",
        "longitude",
        "speed_kmh",
        "distance_km",
        "hour",
        "bearing"
    ]

    X = data[features].replace(
        [np.inf, -np.inf],
        np.nan
    ).fillna(0)

    scaler = StandardScaler()

    X_scaled = scaler.fit_transform(X)

    model = IsolationForest(
        n_estimators=150,
        contamination=contamination,
        random_state=42
    )

    predictions = model.fit_predict(
        X_scaled
    )

    scores = model.decision_function(
        X_scaled
    )

    data["anomaly"] = (
        predictions == -1
    )

    data["anomaly_score"] = -scores

    # Normalize score
    min_score = data["anomaly_score"].min()
    max_score = data["anomaly_score"].max()

    if max_score != min_score:

        data["anomaly_probability"] = (
            (
                data["anomaly_score"]
                - min_score
            )
            /
            (
                max_score
                - min_score
            )
        )

    else:

        data["anomaly_probability"] = 0.0

    return data, model


