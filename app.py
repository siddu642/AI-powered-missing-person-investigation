def create_features(df):

    data = df.copy()

    data["timestamp"] = pd.to_datetime(
        data["timestamp"],
        errors="coerce"
    )

    data = data.dropna()

    data["hour"] = data["timestamp"].dt.hour

    data["day_of_week"] = (
        data["timestamp"].dt.dayofweek
    )

    data["is_weekend"] = (
        data["day_of_week"] >= 5
    ).astype(int)

    data["prev_lat"] = (
        data["latitude"].shift(1)
    )

    data["prev_lon"] = (
        data["longitude"].shift(1)
    )

    data["distance_km"] = haversine(
        data["prev_lat"],
        data["prev_lon"],
        data["latitude"],
        data["longitude"]
    )

    data["distance_km"] = (
        data["distance_km"]
        .fillna(0)
    )

    time_diff = (
        data["timestamp"]
        .diff()
        .dt.total_seconds()
        / 3600
    )

    data["time_diff_hours"] = (
        time_diff
        .replace(0, np.nan)
        .fillna(0.0833)
    )

    data["speed_kmh"] = (
        data["distance_km"]
        / data["time_diff_hours"]
    )

    data["speed_kmh"] = (
        data["speed_kmh"]
        .replace(
            [np.inf, -np.inf],
            np.nan
        )
        .fillna(0)
        .clip(0, 200)
    )

    data["bearing"] = bearing(
        data["prev_lat"].fillna(
            data["latitude"]
        ),
        data["prev_lon"].fillna(
            data["longitude"]
        ),
        data["latitude"],
        data["longitude"]
    )

    data["rolling_speed"] = (
        data["speed_kmh"]
        .rolling(10)
        .mean()
        .fillna(data["speed_kmh"])
    )

    data["rolling_distance"] = (
        data["distance_km"]
        .rolling(10)
        .sum()
        .fillna(data["distance_km"])
    )

    data = data.replace(
        [np.inf, -np.inf],
        np.nan
    )

    data = data.dropna()

    return data.reset_index(drop=True)


