# SEARCH AREA GENERATION
# ============================================================

def generate_search_areas(
    predicted_lat,
    predicted_lon,
    radius_km=2.0
):

    # Approximate degree conversion
    lat_degree = radius_km / 111

    lon_degree = (
        radius_km
        /
        (
            111
            *
            max(
                math.cos(
                    math.radians(
                        predicted_lat
                    )
                ),
                0.1
            )
        )
    )

    offsets = [
        (0, 0),
        (0.5, 0.5),
        (0.5, -0.5),
        (-0.5, 0.5),
        (-0.5, -0.5),
        (1, 0),
        (-1, 0),
        (0, 1),
        (0, -1)
    ]

    results = []

    for i, (x, y) in enumerate(offsets):

        lat = (
            predicted_lat
            + x * lat_degree
        )

        lon = (
            predicted_lon
            + y * lon_degree
        )

        # Center receives highest ranking
        score = 100 - (
            abs(x) + abs(y)
        ) * 15

        results.append({
            "Area": f"Search Zone {i + 1}",
            "Latitude": lat,
            "Longitude": lon,
            "Priority Score": max(
                10,
                round(score, 2)
            )
        })

    return pd.DataFrame(results).sort_values(
        "Priority Score",
        ascending=False
    )


