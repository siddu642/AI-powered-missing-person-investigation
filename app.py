def generate_predicted_route(
    current_lat,
    current_lon,
    predicted_lat,
    predicted_lon,
    steps=20
):

    lats = np.linspace(
        current_lat,
        predicted_lat,
        steps
    )

    lons = np.linspace(
        current_lon,
        predicted_lon,
        steps
    )

    route = pd.DataFrame({
        "latitude": lats,
        "longitude": lons
    })

    return route


